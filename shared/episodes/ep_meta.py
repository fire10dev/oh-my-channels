"""Write <episode>/metadata/{long.md, shorts.md, scheduler.md} from YT Hub (the source of truth). Any channel.

Usage: python3 shared/episodes/ep_meta.py <episode-dir> [<episode-dir> …]
       python3 shared/episodes/ep_meta.py channels/rice-and-empires/episodes/*/ channels/rice-and-empires/episodes/standalone-shorts/*/
Episode dir = folder with ep.json {"code": "L009", "channel": "Rice and Empires", ...}. Videos of the episode = the code itself
plus every hub code starting with "<code>-" (L009-SH1 …). Re-run after `ythub set` (title, description, schedule …).
scheduler.md keeps everything below the line "## Ghi chú" (hand-written plan/notes survive regeneration).
"""
import json, pathlib, subprocess, sys

KEEP = '## Ghi chú'


def hub(*a):
    return json.loads(subprocess.check_output(['ythub', '--json', *a], text=True))


def rel(p, base):
    if not p:
        return '—'
    try:
        return pathlib.Path(p).resolve().relative_to(base.resolve()).as_posix()
    except ValueError:
        return p


def block(v, base):
    out = [f"## {v['code']} — {v['title'] or '(chưa có tiêu đề)'}", '',
           f"- Trạng thái: **{v['stage']}** · Lịch/đăng (+07): {v.get('published_at') or '—'} · YouTube: {v.get('yt_url') or '—'}",
           f"- File: `{rel(v.get('file_path'), base)}` · Thumbnail: `{rel(v.get('thumb_path'), base)}`",
           f"- Related video: {v.get('linked_url') or '—'}", f"- Tags: {v.get('tags') or '—'}", '', '**Description**', '', '```',
           (v.get('description') or '').strip() or '(trống)', '```', '', '**Pinned comment**', '', (v.get('pinned_comment') or '').strip() or '(trống)', '']
    return '\n'.join(out)


def run(d: pathlib.Path):
    ep = json.loads((d / 'ep.json').read_text())
    code, ch = ep['code'], ep['channel']
    vids = sorted((v for v in hub('list', '--channel', ch) if v['code'] == code or v['code'].startswith(code + '-')), key=lambda v: v['code'])
    full = [hub('show', v['code'], '--channel', ch) for v in vids]
    m = d / 'metadata'
    m.mkdir(exist_ok=True)
    head = f"<!-- generated by shared/episodes/ep_meta.py from YT Hub — edit via `ythub set`, then re-run -->\n# {d.name} — "
    main = [v for v in full if v['code'] == code]
    shorts = [v for v in full if v['code'] != code]
    (m / ('long.md' if (d / 'long').is_dir() else 'video.md')).write_text(head + 'video chính\n\n' + '\n'.join(block(v, d) for v in main))
    if shorts:
        (m / 'shorts.md').write_text(head + f'{len(shorts)} short\n\n' + '\n'.join(block(v, d) for v in shorts))
    sched = m / 'scheduler.md'
    notes = ''
    if sched.exists() and KEEP in sched.read_text():
        notes = sched.read_text().split(KEEP, 1)[1]
    rows = sorted(full, key=lambda v: (v.get('published_at') or '9999', v['code']))
    t = [head + 'lịch đăng', '', 'Giờ +07. Nguồn: YT Hub (`published_at` = giờ đã đăng hoặc giờ hẹn). Trống = chưa lên lịch.', '',
         '| Video | Loại | Trạng thái | Lịch / đăng (+07) | YouTube | Related |', '|---|---|---|---|---|---|']
    t += [f"| {v['code']} — {(v['title'] or '')[:60]} | {v['kind']} | {v['stage']} | {v.get('published_at') or '—'} | {v.get('yt_url') or '—'} | {v.get('linked_url') or '—'} |" for v in rows]
    sched.write_text('\n'.join(t) + '\n\n' + KEEP + (notes if notes else '\n\n(Kế hoạch / đề xuất lịch viết tay ở đây — giữ nguyên khi chạy lại.)\n'))
    print(f'{d.name}: {len(full)} video')


for a in sys.argv[1:]:
    p = pathlib.Path(a)
    if (p / 'ep.json').exists():
        run(p)
